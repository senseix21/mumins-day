package com.senseix21.muminsday.packs

import com.senseix21.muminsday.quran.SurahNumber
import com.senseix21.muminsday.quran.VerseRef
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.time.Duration
import kotlin.io.path.createTempDirectory
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertIs
import kotlin.test.assertTrue

/**
 * The shell downloader (ADR-25) against a local HTTPS server, with the TEST PACK fixtures in `src/test/resources/packs`.
 * Nothing here is tafsir or recitation: the "tafsir" is a repeated line that says it is not one, and the "recitation"
 * is a triangle-wave tone generated by [tone].
 */
class DownloaderTest {

    private val resources = File("src/test/resources/packs")
    private val packs = (parseManifest(File(resources, "test-manifest.txt").readText()) as ManifestParse.Accepted).packs
    private val tafsir = packs.single { it.kind == PackKind.Tafsir }
    private val audio = packs.single { it.kind == PackKind.Audio }
    private val server = TestServer()
    private val root = createTempDirectory("packs").toFile()
    private val files = PackFiles(root)

    init {
        for (pack in packs) for (file in pack.files) server.behaviours[file.path.value] = Behaviour.Serve(bytesOf(file))
    }

    @AfterTest
    fun close() {
        server.close()
        root.deleteRecursively()
    }

    private fun bytesOf(file: PackFile): ByteArray = File(resources, file.path.value.removePrefix("test/")).readBytes()

    /** Runs a download as the app does and folds its events through core's `step`, from a tap. */
    private fun run(pack: Pack, cancelled: () -> Boolean = { false }): Pair<List<DownloadEvent>, DownloadState> {
        val events = mutableListOf<DownloadEvent>()
        downloadPack(files, pack, { server.url(it.value) }, cancelled, { events += it }, server.clientSockets)
        var state = step(files.state(pack).let { if (it is DownloadState.Ready) DownloadState.Absent else it }, DownloadEvent.Tap, pack.size)
        for (event in events) state = step(state, event, pack.size)
        return events to state
    }

    @Test
    fun `a whole pack downloads, each file is checked, and the requests carry nothing but what is needed`() {
        val (_, state) = run(audio)
        assertEquals(DownloadState.Ready(audio.size), state)
        for (file in audio.files) assertContentEquals(bytesOf(file), files.fileOf(audio, file).readBytes())
        assertIs<Verified.Intact>(files.verified(audio))
        assertEquals(2, server.requests.size)
        for (request in server.requests) {
            assertTrue(request.line.matches(Regex("GET /test/[a-z.-]+ HTTP/1.1")), request.line)
            val allowed = setOf("host", "user-agent", "accept", "accept-encoding", "connection", "cache-control", "pragma")
            assertTrue(request.headers.keys.all { it in allowed }, "unexpected headers ${request.headers.keys - allowed}")
            assertEquals(PACK_USER_AGENT, request.headers["user-agent"])
            assertEquals("identity", request.headers["accept-encoding"])
            assertFalse("range" in request.headers, "a fresh download asks for the whole file")
        }
    }

    @Test
    fun `an interrupted download resumes with a Range request and ends byte for byte`() {
        val file = tafsir.main
        server.behaviours[file.path.value] = Behaviour.Serve(bytesOf(file), cutAfter = 70_000)
        val (first, stopped) = run(tafsir)
        assertEquals(DownloadEvent.Lost(DownloadFailure.Network), first.last())
        assertEquals(DownloadState.Failed(DownloadFailure.Network, ByteCount(70_000), tafsir.size), stopped)
        assertEquals(70_000L, files.partOf(tafsir, file).length())
        assertEquals(DownloadState.Stopped(ByteCount(70_000), tafsir.size), files.state(tafsir))

        server.behaviours[file.path.value] = Behaviour.Serve(bytesOf(file))
        val (_, ready) = run(tafsir)
        assertEquals(DownloadState.Ready(tafsir.size), ready)
        assertEquals("bytes=70000-", server.requests.last().headers["range"])
        assertContentEquals(bytesOf(file), files.fileOf(tafsir, file).readBytes())
        assertFalse(files.partOf(tafsir, file).exists())
    }

    @Test
    fun `a server that ignores the range sends the file again and the result is still exact`() {
        val file = tafsir.main
        files.partOf(tafsir, file).apply { parentFile!!.mkdirs() }.writeBytes(bytesOf(file).copyOf(5_000))
        server.behaviours[file.path.value] = Behaviour.Serve(bytesOf(file), ignoreRange = true)
        val (events, state) = run(tafsir)
        assertEquals(DownloadState.Ready(tafsir.size), state)
        assertTrue(events.filterIsInstance<DownloadEvent.Progress>().all { it.received <= tafsir.size }, "the count never passes the size")
        assertContentEquals(bytesOf(file), files.fileOf(tafsir, file).readBytes())
    }

    @Test
    fun `cancel stops after the current read and keeps what came, and delete removes every byte`() {
        var reads = 0
        val (events, state) = run(tafsir, cancelled = { reads++ > 1 })
        assertEquals(DownloadEvent.Cancel, events.last())
        assertIs<DownloadState.Stopped>(state)
        val kept = files.partOf(tafsir, tafsir.main).length()
        assertTrue(kept in 1 until tafsir.main.size.bytes, "kept $kept bytes")
        assertEquals(ByteCount(kept), files.used())
        files.delete(tafsir)
        assertEquals(ByteCount.ZERO, files.used())
        assertEquals(DownloadState.Absent, files.state(tafsir))
    }

    @Test
    fun `a file that does not match its SHA-256 is deleted and never gets its final name`() {
        val file = audio.main
        val tampered = bytesOf(file).copyOf().also { it[100] = (it[100].toInt() xor 1).toByte() }
        server.behaviours[file.path.value] = Behaviour.Serve(tampered)
        val (events, state) = run(audio)
        assertEquals(DownloadEvent.HashMismatched, events.last())
        assertEquals(DownloadState.Failed(DownloadFailure.HashMismatch, ByteCount.ZERO, audio.size), state)
        assertFalse(files.fileOf(audio, file).exists())
        assertFalse(files.partOf(audio, file).exists())
        assertEquals(1, server.requests.size, "the timings file is not fetched after the audio failed")
    }

    @Test
    fun `a checked file that changes on the phone is caught before use and the pack is deleted`() {
        assertIs<DownloadState.Ready>(run(audio).second)
        files.fileOf(audio, audio.main).appendBytes(byteArrayOf(0))
        assertEquals(Verified.Removed, files.verified(audio))
        assertEquals(DownloadState.Absent, files.state(audio))
    }

    @Test
    fun `a body longer than the manifest's size is cut off and deleted`() {
        val file = audio.timings!!
        server.behaviours[file.path.value] = Behaviour.Serve(bytesOf(file) + "EXTRA".toByteArray())
        val (events, _) = run(audio)
        assertEquals(DownloadEvent.Lost(DownloadFailure.TooLarge), events.last())
        assertFalse(files.partOf(audio, file).exists())
    }

    @Test
    fun `plain http is refused before any connection, and a redirect is not followed`() {
        val file = tafsir.main
        val http = fetchFile("http://localhost:${server.port}/${file.path.value}", files.partOf(tafsir, file), file, { false }, {}, server.clientSockets)
        assertEquals(Fetched.Failed(DownloadFailure.Refused), http)
        assertEquals(0, server.requests.size)

        server.behaviours[file.path.value] = Behaviour.Status(302, location = server.url("elsewhere"))
        server.behaviours["elsewhere"] = Behaviour.Serve(bytesOf(file))
        val redirected = fetchFile(server.url(file.path.value), files.partOf(tafsir, file), file, { false }, {}, server.clientSockets)
        assertEquals(Fetched.Failed(DownloadFailure.Refused), redirected)
        assertEquals(1, server.requests.size, "the redirect's target was never asked for")
    }

    @Test
    fun `a 416 to a resume deletes the partial file so the next tap starts fresh`() {
        val file = tafsir.main
        files.partOf(tafsir, file).apply { parentFile!!.mkdirs() }.writeBytes(ByteArray(10))
        server.behaviours[file.path.value] = Behaviour.Status(416)
        assertEquals(Fetched.Failed(DownloadFailure.Refused), fetchFile(server.url(file.path.value), files.partOf(tafsir, file), file, { false }, {}, server.clientSockets))
        assertFalse(files.partOf(tafsir, file).exists())
    }

    // ----- the FAKE tone pack and its timings -----

    /** The fixture's generator: 1.5 s of an 8-bit, 8 kHz triangle wave, integers only, so it is the same on any machine. */
    private fun tone(): ByteArray {
        val samples = ByteArray(12_000) { n ->
            val phase = n % 20
            (if (phase < 10) 28 + phase * 20 else 28 + (20 - phase) * 20).toByte()
        }
        val header = ByteBuffer.allocate(44).order(ByteOrder.LITTLE_ENDIAN).apply {
            put("RIFF".toByteArray()); putInt(36 + samples.size); put("WAVE".toByteArray())
            put("fmt ".toByteArray()); putInt(16); putShort(1); putShort(1); putInt(8000); putInt(8000); putShort(1); putShort(8)
            put("data".toByteArray()); putInt(samples.size)
        }.array()
        return header + samples
    }

    @Test
    fun `the tone fixture is exactly what its generator makes, and its timings fit inside it`() {
        assertContentEquals(tone(), bytesOf(audio.main))
        val durationMillis = (bytesOf(audio.main).size - 44) * 1000L / 8000
        val timings = (parseTimings(bytesOf(audio.timings!!).toString(Charsets.UTF_8)) as TimingsParse.Parsed).timings
        assertTrue(timings.last().end <= Duration.ofMillis(durationMillis))
        val first = VerseRef(SurahNumber.of(1)!!, 1)
        assertEquals(AyahAt.At(first), ayahAt(timings, Duration.ZERO))
        assertEquals(AyahAt.Between, ayahAt(timings, Duration.ofMillis(950)), "the fixture's gap")
        assertEquals(AyahAt.Between, ayahAt(timings, Duration.ofMillis(durationMillis)))
        assertTrue(packs.all { "TEST PACK" in it.name })
    }
}
